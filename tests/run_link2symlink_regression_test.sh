#!/bin/sh
# Run the link2symlink regression suite against a real PRoot binary.
#
# PRoot drives the tracee with ptrace(2), so it can't be run nested under
# another ptrace-based sandbox: this script refuses to run there instead of
# letting every case fail (or, worse, be skipped) for the wrong reason.  It
# is meant for a glibc host -- a GitHub ubuntu runner, typically:
#
#     sudo apt-get install -y libtalloc-dev clang lld
#     sh tests/run_link2symlink_regression_test.sh
#
# Why not the local sandbox: this fork's src/syscall/rlimit.c uses glibc's
# struct rlimit64, which musl doesn't have (pre-existing; it fails the same
# way on the baseline commit), and PRoot can't run nested anyway.
#
# What the script takes care of, since a bare "make" doesn't work on a plain
# Ubuntu image:
#   * the loader is linked with --rosegment, which GNU bfd doesn't know:
#     clang + lld are used when CC/LD aren't given (override with CC=... LD=...);
#   * only the 64-bit loader is built unless L2S_LOADER_32=1 -- the suite
#     runs 64-bit programs, and -m32 needs a multilib toolchain;
#   * linux/ashmem.h may be gone from the kernel headers (the extension is
#     compiled whatever its configuration): a minimal copy of that UAPI
#     header is dropped into the *scratch* source tree, never into the
#     repository, and only when the system headers lack it;
#   * everything is built in a scratch copy of the tree, so no .o, .d or
#     generated file lands in the working tree.
#
# Exit status:
#   0  every test passed
#   1  a test failed, or one of the required tests was skipped
#   2  PRoot couldn't be built
#   3  the built PRoot can't run here (no ptrace, ...)
#   125 the environment is missing something (tools, /proc, ...)
#
# Environment: CC, LD, JOBS (default 2), TMPDIR, KEEP=1 to keep the scratch
# tree, L2S_LOADER_32=1 to build the 32-bit loader too.

set -u

HERE=$(cd "$(dirname "$0")" && pwd)
SRC=$(cd "$HERE/.." && pwd)
L2S=$HERE/l2s
JOBS=${JOBS:-2}
TMP=${TMPDIR:-/tmp}
WORK=
KEEP=${KEEP:-0}

say() { printf '%s\n' "$*"; }

cleanup() {
	if [ -n "$WORK" ] && [ "$KEEP" != 1 ]; then
		rm -rf "$WORK"
	fi
}
trap cleanup EXIT INT TERM

# 1. What the suite needs ------------------------------------------------
# Headers are probed with the compiler: on a multiarch distribution
# sys/ptrace.h lives under /usr/include/<triplet>/, and probing is the only
# way not to skip the whole suite for a path that isn't where one guessed.
probe_cc=${CC:-cc}
missing=
for tool in "$probe_cc" make mcookie ln stat find readlink timeout sed; do
	command -v "$tool" >/dev/null 2>&1 || missing="$missing $tool"
done

PROBE=$TMP/l2s-probe.$$.c
printf '#include <sys/ptrace.h>\n#include <talloc.h>\nint main(void) { return 0; }\n' > "$PROBE"
if ! "$probe_cc" "$PROBE" -ltalloc -o "$PROBE.bin" >/dev/null 2>&1; then
	missing="$missing <sys/ptrace.h+libtalloc-dev>"
fi
rm -f "$PROBE" "$PROBE.bin"

if [ -n "$missing" ]; then
	say "SKIP: missing:$missing"
	exit 125
fi

# 2. Is PRoot able to run at all here? -----------------------------------
tracer=$(sed -n 's/^TracerPid:[[:space:]]*//p' /proc/self/status 2>/dev/null | tr -d ' ')
if [ -n "${tracer:-}" ] && [ "$tracer" != 0 ]; then
	say "SKIP: this shell is already traced by pid $tracer (nested PRoot/ptrace"
	say "      sandbox).  PRoot crashes when nested, so the suite is not run."
	say "      Run it on a glibc host: GitHub ubuntu runner."
	exit 125
fi

# 3. Build the real thing, in a scratch copy of the tree ------------------
WORK=$(mktemp -d "$TMP/l2s-regression.XXXXXX") || exit 125
BUILD=$WORK/proot
LOG=$WORK/build.log

say "== copying $SRC to $BUILD"
mkdir -p "$BUILD"
if ! ( cd "$SRC" && tar cf - --exclude=.git . ) | ( cd "$BUILD" && tar xf - ); then
	say "FAIL: can't copy the tree to $BUILD"
	exit 2
fi

# The Android UAPI header the ashmem_memfd extension includes
# unconditionally.  Recent kernel headers dropped it; the extension is not
# part of what this suite exercises, so a copy of the definitions it uses
# goes into the scratch tree -- never into the repository.
SHIMMED=
if ! printf '#include <linux/ashmem.h>\nint main(void) { return 0; }\n' \
	| "$probe_cc" -x c - -o "$WORK/ashmem-probe" >/dev/null 2>&1; then
	mkdir -p "$BUILD/src/linux"
	cat > "$BUILD/src/linux/ashmem.h" <<'ASHMEM'
/*
 * Minimal copy of the Android UAPI header, for building PRoot on a host
 * whose kernel headers no longer carry it.  Generated by
 * tests/run_link2symlink_regression_test.sh into a scratch tree; it is
 * not part of the repository.  Only what src/extension/ashmem_memfd
 * uses is defined.
 */
#ifndef _LINUX_ASHMEM_H
#define _LINUX_ASHMEM_H

#include <linux/ioctl.h>
#include <linux/types.h>

#define __ASHMEMIOC 0x77

#define ASHMEM_NAME_LEN 256

#define ASHMEM_SET_NAME _IOW(__ASHMEMIOC, 1, char[ASHMEM_NAME_LEN])
#define ASHMEM_GET_NAME _IOR(__ASHMEMIOC, 2, char[ASHMEM_NAME_LEN])
#define ASHMEM_SET_SIZE _IOW(__ASHMEMIOC, 3, size_t)
#define ASHMEM_GET_SIZE _IO(__ASHMEMIOC, 4)

#endif /* _LINUX_ASHMEM_H */
ASHMEM
	SHIMMED=" (with a scratch linux/ashmem.h)"
fi

# clang + lld link the loader: its LDFLAGS carry --rosegment, which GNU bfd
# doesn't know.  CC/LD from the environment win.
if [ -z "${CC:-}" ] && command -v clang >/dev/null 2>&1 && command -v ld.lld >/dev/null 2>&1; then
	CC=clang
	LD="clang -fuse-ld=lld"
	say "   using clang + ld.lld for the loader"
fi
CC=${CC:-cc}
LD=${LD:-$CC}

# The 32-bit loader needs a multilib toolchain and isn't used by the suite.
if [ "${L2S_LOADER_32:-0}" = 1 ]; then
	LOADER_32=
else
	LOADER_32=HAS_LOADER_32BIT=
fi

say "== building PRoot${SHIMMED}"
if ! env CC="$CC" LD="$LD" make -C "$BUILD/src" -j"$JOBS" $LOADER_32 >"$LOG" 2>&1; then
	say "FAIL: build failed; last lines of $LOG:"
	tail -n 40 "$LOG"
	say "      (keep the scratch tree with KEEP=1, or pass CC=/LD= yourself)"
	exit 2
fi

PROOT=$BUILD/src/proot
if [ ! -x "$PROOT" ]; then
	say "FAIL: $PROOT was not built"
	exit 2
fi
say "   $PROOT"

# 4. Does the built binary trace a simple tracee? -------------------------
if ! "$PROOT" -l /bin/true >"$LOG" 2>&1; then
	say "FAIL: the built PRoot can't run here: $PROOT -l /bin/true"
	tail -n 20 "$LOG"
	exit 3
fi

# 5. The guest binaries a couple of tests execute -------------------------
ROOTFS=$WORK/rootfs
mkdir -p "$ROOTFS/bin" "$WORK/tmp"

build_static() {
	if ! "$CC" -static -O2 "$1" -o "$2" >"$LOG" 2>&1; then
		say "   note: can't build $2 (static linking unavailable);"
		say "         the tests that need it will skip."
		return 1
	fi
	return 0
}

build_static "$HERE/puts_proc_self_exe.c" "$ROOTFS/bin/puts_proc_self_exe" || true
build_static "$L2S/open_nofollow.c" "$ROOTFS/bin/open_nofollow" || true

# 6. Run the cases --------------------------------------------------------
# These carry the acceptance criteria of the batch this suite was written
# for; skipping one of them is not a pass.
REQUIRED="test-9f16ee06.sh test-ad207330.sh test-4e91b60a.sh test-l2s-legacy-chain.sh"

pass=0
skip=0
fail=0
skipped=
failed=

for test in "$L2S"/test-*.sh; do
	name=$(basename "$test")
	out=$(PROOT="$PROOT" PROOT_RAW="$PROOT" ROOTFS="$ROOTFS" TMPDIR="$WORK/tmp" \
		PROOT_TMP_DIR="$WORK/tmp" timeout 300 sh -e "$test" 2>&1)
	status=$?

	case $status in
	0)
		pass=$((pass + 1))
		say "PASS $name"
		;;
	125)
		skip=$((skip + 1))
		skipped="$skipped $name"
		say "SKIP $name (its prerequisites are missing here)"
		;;
	*)
		fail=$((fail + 1))
		failed="$failed $name"
		say "FAIL $name (exit $status)"
		printf '%s\n' "$out" | sed 's/^/     /' | tail -n 25
		;;
	esac
done

say ""
say "== $pass passed, $skip skipped, $fail failed"
[ -n "$skipped" ] && say "   skipped, not counted as passed:$skipped"

if [ "$fail" -ne 0 ]; then
	say "   failed:$failed"
	exit 1
fi

if [ "$pass" -eq 0 ]; then
	say "FAIL: every test was skipped -- that is not a pass"
	exit 1
fi

for name in $REQUIRED; do
	case " $skipped " in
	*" $name "*)
		say "FAIL: $name carries an acceptance criterion of this batch but was skipped"
		exit 1
		;;
	esac
done

exit 0
